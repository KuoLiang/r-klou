# 4-1 用亂數練習，這裡改用真實的銷售資料回答兩個問題：
#   1. 不同員工的平均銷售額是否不同？（ANOVA）
#   2. 不同年份的平均銷售額是否不同？（ANOVA，再用 t 檢定兩兩比較）
#
# 說明：這個範例原本從資料庫讀取資料。以下的 #> 是改用 NWSales.csv
#       （和資料庫查詢結果相同的 2155 筆資料）實際執行的結果。
# ============================================================

library(dplyr)
source("../mysql_conn.R")
#  執行上一層資料夾的 mysql_conn.R：連線資料庫並送出查詢
#  ../ 代表「上一層資料夾」，所以工作目錄必須設在 4-Statistics
#  （上一層的 mysql_conn.R 用的資料表名稱是 orderdetails，
#   3-Plot 資料夾裡的版本則是 order_details；如果查詢出錯，請確認資料庫中的實際名稱）
nw <-  fetch(myquery_result, n=-1)
#  把查詢結果全部抓回來
#  沒有資料庫連線時這裡會出錯，可以改用 CSV：nw <- read.csv("../NWSales.csv")
##########################################
#transform
##########################################
nw$Year = factor(nw$Year)
nw$EmployeeID = factor(nw$EmployeeID)
nw$ShipCountry = factor(nw$ShipCountry)
#  ANOVA 的分組變數一定要是 factor（類別）！
#  如果 EmployeeID 還是數字，aov() 會把它當成連續變數做迴歸，結果完全不同

# ------------------------------------------------------------
# 第一部分：不同員工的銷售額是否不同？
# ------------------------------------------------------------
result=aov(Sales~EmployeeID,data=nw)
#  單因子變異數分析：Sales 依 EmployeeID 分成 9 組
#  H0：9 位員工的平均銷售額都相同
summary(result)
#>               Df    Sum Sq Mean Sq F value Pr(>F)
#> EmployeeID     8 1.999e+07 2498138   2.337 0.0169 *
#> Residuals   2146 2.294e+09 1068956
#  Df = 8：9 組 - 1；1.999e+07 是科學記號，等於 19,990,000
#  p = 0.0169 < 0.05 → 顯著，至少有一位員工的平均銷售額和其他人不同
#  （想知道是哪幾位，可以接著做事後檢定：TukeyHSD(result)）
plot(nw$Sales~nw$EmployeeID)
#  各員工銷售額的箱形圖。銷售額有很多很大的離群值，箱子會被壓得很扁

# ------------------------------------------------------------
# 第二部分：不同年份的銷售額是否不同？
# ------------------------------------------------------------
result=aov(Sales~Year,data=nw)
summary(result)
#>               Df    Sum Sq Mean Sq F value Pr(>F)
#> Year           2 4.753e+06 2376712   2.215  0.109
#> Residuals   2152 2.309e+09 1073053
#  p = 0.109 > 0.05 → 不顯著，三個年份的平均銷售額沒有顯著差異
plot(nw$Sales~nw$Year)

###########################################
# ------------------------------------------------------------
# 第三部分：年份兩兩比較（t 檢定）
# ------------------------------------------------------------
x <- nw %>% filter(Year == 1994)
y <- nw %>% filter(Year == 1995)
z <- nw %>% filter(Year == 1996)
#  依年份切成三份：1994 年 324 筆、1995 年 1026 筆、1996 年 805 筆
t.test(x$Sales,y$Sales,var.equal = T)
#> t = -1.3367, df = 1348, p-value = 0.1816
#> mean of x mean of y
#>  541.1886  615.8537
#  1994 vs 1995：p = 0.18，不顯著
t.test(x$Sales,z$Sales,var.equal = T)
#> t = -1.8272, df = 1127, p-value = 0.06794
#> mean of x mean of y
#>  541.1886  679.8107
#  1994 vs 1996：p = 0.068，接近但未達 0.05，不顯著
t.test(y$Sales,z$Sales,var.equal = T)
#> t = -1.2725, df = 1829, p-value = 0.2034
#  1995 vs 1996：p = 0.20，不顯著
#
#  三次比較都不顯著，和上面 ANOVA 的結論一致。
#  兩點提醒：
#   1. 這裡直接假設變異數相同 (var.equal = T)，比較嚴謹的做法是先用 var.test() 檢查
#   2. 兩兩做 3 次 t 檢定會累積誤判機率（見 4-1 說明），ANOVA 後的事後檢定比較適合

