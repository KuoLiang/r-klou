# ============================================================
# 4-1 假設檢定入門：常態檢定、t 檢定、F 檢定、變異數分析 (ANOVA)
# ============================================================
# 【先懂這幾個觀念】
#   虛無假設 H0：「沒有差異」，例如「平均數等於 5」
#   對立假設 H1：「有差異」，例如「平均數不等於 5」
#   p 值 (p-value)：假設 H0 是對的，還會看到這麼極端（或更極端）結果的機率
#     p < 0.05 → 結果「顯著」，拒絕 H0，認為有差異
#     p ≥ 0.05 → 結果「不顯著」，不拒絕 H0（注意：不代表證明了「沒有差異」）
#   0.05 稱為「顯著水準」α，是常用的門檻
#
# 這個範例用「自己產生的亂數」當資料。因為我們知道真正的平均數和標準差，
# 就能檢查檢定結果是否正確。
#
# 重要：rnorm() 每次執行都會產生不同的亂數，所以你看到的數字會和下面的 #> 不同，
#    甚至「顯著 / 不顯著」的結論也可能不一樣（第三部分有說明各結論出現的機率）。
#    想讓每次結果都相同，可以在最前面加上 set.seed(2026)。
#    下面的 #> 是 R 4.6.1 在 set.seed(2026) 時實際執行的結果。
# ============================================================
library(ggplot2)
# ------------------------------------------------------------
# 第一部分：產生亂數資料
# ------------------------------------------------------------
x <-  rnorm(30,5,1) #30個隨機數，平均數5，標準差1
y <-  rnorm(30,4,1) #30個隨機數，平均數4，標準差1
y1 <-  rnorm(30,4,2) #30個隨機數，平均數4，標準差2
#  rnorm(個數, 平均數, 標準差)：從常態分配（鐘形曲線）隨機抽出數字
#  r = random（隨機）、norm = normal（常態）
#  注意：抽出來的 30 個數字，平均數「接近」5，但不會剛好是 5

# ------------------------------------------------------------
# 第二部分：常態性檢定
# ------------------------------------------------------------
# 【補充】t 檢定假設資料大致是常態分配，所以先檢查。
#   Shapiro-Wilk 檢定的 H0：「資料是常態分配」
#   p ≥ 0.05 → 不拒絕 H0 → 可以當作常態分配
shapiro.test(x)   #檢視是否常態分配
#> W = 0.9608, p-value = 0.3246      ← p > 0.05，可視為常態
shapiro.test(y)   #檢視是否常態分配
#> W = 0.94175, p-value = 0.1014
shapiro.test(y1)   #檢視是否常態分配
#> W = 0.97838, p-value = 0.7811
#  三組都 p > 0.05，符合預期（因為本來就是從常態分配抽出來的）

# ------------------------------------------------------------
# 第三部分：單一樣本 t 檢定（這組資料的平均數是否等於某個值？）
# ------------------------------------------------------------
#單一樣本
# 【補充】t.test(資料, mu = 比較的值)
#   H0：母體平均數 = mu；H1：母體平均數 ≠ mu
#   輸出要看：p-value、95 percent confidence interval（95% 信賴區間）、mean of x（樣本平均）
#   如果 mu 落在 95% 信賴區間外，就等於 p < 0.05
t.test(x, mu = 5) #檢定 x 是否與 5   顯著差異, 結果不顯著，不拒絕 H0
#> 	One Sample t-test
#> data:  x
#> t = -0.36209, df = 29, p-value = 0.7199
#> alternative hypothesis: true mean is not equal to 5
#> 95 percent confidence interval:
#>  4.518468 5.336675
#> sample estimates:
#> mean of x
#>  4.927572
#  t = 檢定統計量；df = 自由度（樣本數 - 1 = 29）
#  p = 0.72 > 0.05 → 不顯著。5 落在信賴區間 4.52 ~ 5.34 內
t.test(x, mu = 4) #檢定 x 是否與 4   顯著差異, 結果顯著  ，拒絕 H0
#> t = 4.6372, df = 29, p-value = 6.946e-05
#  6.946e-05 是科學記號，等於 0.00006946，遠小於 0.05 → 顯著
t.test(y, mu = 5) #檢定 y 是否與 5   顯著差異, 結果顯著  ，拒絕 H0
#> t = -8.0985, df = 29, p-value = 6.249e-09
t.test(y, mu = 4) #檢定 y 是否與 4   顯著差異, 結果不顯著，不拒絕 H0
#> t = -1.0433, df = 29, p-value = 0.3054
t.test(y1, mu = 5) #檢定 y1 是否與 5 顯著差異, 結果顯著  ，拒絕 H0
#> t = -2.3434, df = 29, p-value = 0.02618
t.test(y1, mu = 4) #檢定 y1 是否與 4 顯著差異, 結果不顯著，不拒絕 H0
#> t = 0.17195, df = 29, p-value = 0.8647
#
#  【結論不一定每次都相同】用電腦重複模擬 2000 次，各結論出現的比例：
#    x 與 5、y 與 4、y1 與 4（真的沒差異）：約 95% 不顯著，約 5% 會誤判為顯著
#      → 這 5% 就是「型一錯誤」，也就是顯著水準 α = 0.05 的意思
#    x 與 4、y 與 5（差 1，標準差 1）：幾乎 100% 顯著
#    y1 與 5（差 1，但標準差是 2）：只有約 76% 顯著
#      → 資料越分散，越難偵測出差異；約 1/4 的機會會得到「不顯著」

# ------------------------------------------------------------
# 第四部分：F 檢定（兩組的變異數是否相同？）
# ------------------------------------------------------------
## F 檢定
# 【補充】var.test(組1, 組2)：H0 是「兩組的變異數相同」
#   做兩組 t 檢定之前，先用它決定 var.equal 要設 TRUE 還是 FALSE
var.test(x, y)  #x,y  母體變異數相同
#> F = 1.9915, num df = 29, denom df = 29, p-value = 0.06853
#> ratio of variances
#>           1.991549
#  F = 兩組變異數的比值。p = 0.069 > 0.05 → 不拒絕「變異數相同」
var.test(x, y1) #x,y1 母體變異數不相同
#> F = 0.25315, num df = 29, denom df = 29, p-value = 0.0004036
#  p < 0.05 → 變異數不同（y1 的標準差是 2，x 是 1）

# ------------------------------------------------------------
# 第五部分：獨立樣本 t 檢定（兩組的平均數是否相同？）
# ------------------------------------------------------------
#獨立樣本 t 檢定
t.test(x,y,var.equal = T)  #x,y 母體變異數相同
#> 	Two Sample t-test
#> t = 4.3868, df = 58, p-value = 4.918e-05
#> 95 percent confidence interval:
#>  0.584722 1.566190
#> mean of x mean of y
#>  4.927572  3.852116
#  var.equal = T：變異數相同時使用標準的 t 檢定，df = 30 + 30 - 2 = 58
#  p < 0.05 → 兩組平均數有顯著差異（真實差距是 5 - 4 = 1）
t.test(x,y1,var.equal = F) #x,y1 母體變異數不相同
#> 	Welch Two Sample t-test
#> t = 1.9306, df = 42.798, p-value = 0.06017
#  var.equal = F：變異數不同時，R 改用 Welch t 檢定，自由度會是小數
#  這次 p = 0.06 > 0.05 → 不顯著！
#  其實真實平均數差 1，但因為 y1 很分散，模擬顯示只有約 67% 的機會會顯著。
#  這說明：「不顯著」不等於「沒有差異」，也可能是樣本太少或資料太分散

# ------------------------------------------------------------
# 第六部分：用圖比較三組
# ------------------------------------------------------------
### Visualization

z <- append(x,y)
z <- append(z,y1)
#  append()：把向量接在後面 → z 共 90 個數字（x、y、y1 各 30 個）
class <- factor(rep(1:3,each=30))
#  組別標籤：30 個 1、30 個 2、30 個 3，轉成類別
#  （提醒：class 和內建函數 class() 同名，能執行但容易混淆）
z.dataframe <- data.frame(z,class)
#  組成資料框：每列一個數值和它的組別
a <- ggplot(data=z.dataframe,aes(x=class,y=z))
#  錯誤：沒有這個函式 "ggplot"
#     原因：這個檔案沒有載入 ggplot2。修正：在這行之前加上 library(ggplot2)
a + geom_boxplot()
#  箱形圖：三組的中位數和分散程度；第 3 組 (y1) 的箱子明顯比較長
a + geom_violin()
#  小提琴圖：形狀代表資料分布

# ------------------------------------------------------------
# 第七部分：單因子變異數分析 ANOVA（三組以上的平均數是否相同？）
# ------------------------------------------------------------
#============
#Anova
#============
# 【補充】為什麼不兩兩做 t 檢定？
#   3 組要做 3 次 t 檢定，每次都有 5% 誤判機會，累積起來誤判機率會變大。
#   ANOVA 一次檢定所有組：H0 是「所有組的平均數都相同」
#   如果 ANOVA 顯著，再用「事後檢定」(post hoc) 找出是哪幾組不同
library(report)
#  report 套件：把統計結果自動寫成英文的報告句子
library(multcomp)
#  multcomp 套件：多重比較，用來做事後檢定
#  載入時會出現「載入需要的套件：mvtnorm、survival…」等訊息，是正常的
#  兩個套件都要先安裝：install.packages(c("report", "multcomp"))

z <-  rnorm(90,5,1)  #90個隨機數，平均數5，標準差1
class <-  factor(rep(1:3,each=30)) #類別123 重複30次 total 90
z1 <-  data.frame(z,class)
#  90 個數字都來自「同一個」常態分配，再隨便分成 3 組
#  所以三組的真實平均數都是 5，ANOVA 應該「不顯著」
result <- aov(z~class,data=z1)
#  aov(數值 ~ 組別, data = 資料)：變異數分析
#  公式 z ~ class 讀作「z 依 class 分組」
summary(result)
#>             Df Sum Sq Mean Sq F value Pr(>F)
#> class        2   4.18  2.0887   2.227  0.114
#> Residuals   87  81.59  0.9378
#  Df 自由度、Sum Sq 平方和、Mean Sq 均方、F value F 值、Pr(>F) 就是 p 值
#  class 那一列：組間差異；Residuals：組內差異（誤差）
#  p = 0.114 > 0.05 → 不顯著，三組平均數沒有顯著差異，符合預期
report(result)
#> The ANOVA (formula: z ~ class) suggests that:
#>   - The main effect of class is statistically not significant and small (F(2, 87)
#> = 2.23, p = 0.114; Eta2 = 0.05, 95% CI [0.00, 1.00])
#  自動產生的英文報告：效果「不顯著且小」
#  Eta2（η²）是效果量：組別能解釋多少比例的差異，0.05 代表只解釋 5%
plot(z1$z~z1$class)
#  R 內建 plot() 遇到「數值 ~ 類別」會畫出各組的箱形圖

#post_hoc
#Tukey HSD test
# 【補充】Tukey HSD 是最常用的事後檢定，會比較「每兩組」，並自動校正誤判機率

post_test <- glht(result,linfct = mcp(class = "Tukey")) #指定 class 為比較對象
#  glht()：一般線性假設檢定；mcp(class = "Tukey") 指定用 Tukey 方法比較 class 的各組
summary(post_test)
#>            Estimate Std. Error t value Pr(>|t|)
#> 2 - 1 == 0   0.5277     0.2500   2.110   0.0936 .
#> 3 - 1 == 0   0.2589     0.2500   1.036   0.5566
#> 3 - 2 == 0  -0.2688     0.2500  -1.075   0.5322
#  每一列是一對比較，例如「2 - 1」= 第 2 組平均減第 1 組平均
#  Estimate 差距、Pr(>|t|) 校正後的 p 值；三組比較都 > 0.05，沒有顯著差異
#  星號說明：*** p<0.001、** p<0.01、* p<0.05、. p<0.1
plot(post_test)
#  畫出每對比較的 95% 信賴區間；區間跨過 0（垂直虛線）代表不顯著


###############

z2 <-  c(z,rnorm(30,3,2)) #再加30個隨機數，平均數3，標準差2
class <-  factor(rep(1:4,each=30)) #類別1234 total 120
zc2 <-  data.frame(z2,class)
#  原本的 3 組再加上第 4 組：平均數 3（比其他組低 2）
#  這次 ANOVA 應該「顯著」
result2 <- aov(z2~class,data=zc2)
summary(result2)
#>              Df Sum Sq Mean Sq F value   Pr(>F)
#> class         3  58.01  19.338    13.5 1.29e-07 ***
#> Residuals   116 166.18   1.433
#  p = 0.000000129 < 0.05 → 顯著，至少有一組的平均數不同
report(result2)
#>   - The main effect of class is statistically significant and large (F(3, 116) =
#> 13.50, p < .001; Eta2 = 0.26, 95% CI [0.14, 1.00])
#  效果「顯著且大」，組別解釋了 26% 的差異
plot(zc2$z2~zc2$class)
#  第 4 組的箱子明顯比較低、也比較長

#post_hoc
#Tukey HSD test

post_test <- glht(result2,linfct = mcp(class = "Tukey")) #指定 class 為比較對象
summary(post_test)
#>            Estimate Std. Error t value Pr(>|t|)
#> 2 - 1 == 0   0.5277     0.3090   1.708    0.324
#> 3 - 1 == 0   0.2589     0.3090   0.838    0.836
#> 4 - 1 == 0  -1.2846     0.3090  -4.157   <0.001 ***
#> 3 - 2 == 0  -0.2688     0.3090  -0.870    0.821
#> 4 - 2 == 0  -1.8123     0.3090  -5.864   <0.001 ***
#> 4 - 3 == 0  -1.5436     0.3090  -4.995   <0.001 ***
#  只有和第 4 組有關的比較顯著 → 事後檢定找出「第 4 組和其他組不同」
plot(post_test)
#  和第 4 組有關的三個信賴區間都不跨過 0

# ============================================================
# 重點整理
# ============================================================
# | 想知道什麼                    | 方法                | R 函數                     |
# |-------------------------------|---------------------|----------------------------|
# | 資料是否為常態分配            | Shapiro-Wilk 檢定   | shapiro.test(x)            |
# | 一組平均數是否等於某個值      | 單一樣本 t 檢定     | t.test(x, mu = 5)          |
# | 兩組變異數是否相同            | F 檢定              | var.test(x, y)             |
# | 兩組平均數是否相同            | 獨立樣本 t 檢定     | t.test(x, y, var.equal = ) |
# | 三組以上平均數是否相同        | 變異數分析 ANOVA    | aov(值 ~ 組別)             |
# | ANOVA 顯著後，哪幾組不同      | Tukey 事後檢定      | glht(..., mcp(組別 = "Tukey")) |
#
# 判讀口訣：p < 0.05 → 顯著 → 拒絕 H0 → 有差異
