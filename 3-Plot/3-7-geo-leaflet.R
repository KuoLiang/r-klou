# ============================================================
# 3-7 用 leaflet 畫互動地圖
# ============================================================
# leaflet 可以在 R 裡畫出「可以拖曳、縮放」的互動地圖，
# 並在指定的經緯度放上標記 (marker)，點一下會跳出說明文字 (popup)。
#
# 地圖會顯示在 RStudio 右下角的 Viewer 窗格（不是 Plots 窗格），
# 需要連上網路才能載入地圖底圖。
#
# 小知識：經度 (longitude, lng) 是東西方向，緯度 (latitude, lat) 是南北方向。
#   東經、北緯是正數；西經、南緯是負數。
#   可以在 Google 地圖上按右鍵，查到任何地點的經緯度（顯示順序是「緯度, 經度」）。
# ============================================================

install.packages("leaflet")
#  安裝 leaflet 套件（每次執行都會重新安裝；
#  建議改成 if (!require("leaflet")) install.packages("leaflet")）
library(leaflet)

# ------------------------------------------------------------
# 第一部分：用管線 %>% 一次完成
# ------------------------------------------------------------
m <- leaflet() %>%
  addTiles() %>%  # Add default OpenStreetMap map tiles
  addMarkers(lng=174.768, lat=-36.852, popup="The birthplace of R")
#  leaflet()     ：建立一張空白地圖
#  addTiles()    ：加上地圖底圖（預設使用 OpenStreetMap 開放街圖）
#  addMarkers()  ：在指定位置加上標記
#    lng = 經度、lat = 緯度（-36.852 是南緯，因為在南半球）
#    popup = 點擊標記時跳出的文字
#  這個位置是紐西蘭奧克蘭大學，R 語言最早在這裡開發
#  %>% 會自動從 leaflet 套件載入，不需要另外載入 dplyr
m
#  顯示地圖：可以用滑鼠拖曳、滾輪縮放，點標記會出現 "The birthplace of R"
#########

# ------------------------------------------------------------
# 第二部分：不用管線，一步一步完成
# ------------------------------------------------------------
nthu <- leaflet()
nthu <- addTiles(nthu)
nthu <- addMarkers(nthu, lng=120.9967, lat=24.7961, popup="The NTHU Campus")
#  和上面完全相同的做法，只是每一步都把結果存回 nthu
#  比較兩種寫法：
#    管線寫法   leaflet() %>% addTiles() %>% addMarkers(...)
#    一步一步   nthu <- addTiles(nthu)  …
#  位置是清華大學（東經 120.9967、北緯 24.7961）
nthu
#  顯示地圖，標記在清華大學校園
#########




# ============================================================
# 重點整理
# ============================================================
# | 函數           | 用途                              |
# |----------------|-----------------------------------|
# | leaflet()      | 建立空白地圖                      |
# | addTiles()     | 加上地圖底圖                      |
# | addMarkers()   | 加上標記（lng 經度、lat 緯度）    |
# | popup =        | 點擊標記時顯示的文字              |
#
# 其他常用功能：
#   setView(lng, lat, zoom = 15)       ：設定地圖中心和縮放等級
#   addCircleMarkers(...)              ：圓形標記，可以依數值調整大小顏色
#   addPopups(...)                     ：直接顯示說明框，不用點擊
