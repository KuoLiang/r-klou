hist(iris$Petal.Width)
#  直方圖：把數值切成幾個區間，長條高度代表落在這個區間的筆數
#  注意：上面設定的 mfrow = c(1,3) 還有效，所以這張圖只佔畫面的 1/3

par(mfrow=c(1,3))
