# ------------------------------------------------------------
# 第一部分：複習向量
# ------------------------------------------------------------
x <- c(10.4, 5.6, 3.1, 6.4, 21.7)
x = c(10.4, 5.6, 3.1, 6.4, 21.7)
#  <- 和 = 都是賦值，效果相同
x         #顯示 x
#> [1] 10.4  5.6  3.1  6.4 21.7
y = 1/x   #一次處理vector中所有物件
y
#  每個元素都計算 1 除以它，不用寫迴圈（向量化運算）
#> [1] 0.09615385 0.17857143 0.32258065 0.15625000 0.04608295
y <- c(x, 0, x) #建立vector y,內容為 x0x （x為向量）
y
#  c() 可以把向量和數字接在一起：x 的 5 個 + 0 + x 的 5 個 = 11 個
#> [1] 10.4  5.6  3.1  6.4 21.7  0.0 10.4  5.6  3.1  6.4 21.7

# 【補充】paste() 把文字黏在一起
#   sep = 中間的分隔符號，預設是一個空白
z <- paste("X",1)
#  結果 "X 1"（中間有空白，因為 sep 預設是空白）
z <- paste("Y",c(1:100), sep="") #可用於創造有特殊字首之學號
#  sep = "" 代表不要空白 → "Y1" "Y2" ... "Y100"，共 100 個
z <- paste(c("X","Y","Z"), 100:200, sep="_") #兩個向量元素配對時使用 _ 相連
z
#  兩個向量長度不同時，短的會循環使用：X、Y、Z、X、Y、Z…依序配對 100~200
#> [1] "X_100" "Y_101" "Z_102" "X_103" "Y_104" "Z_105" "X_106" "Y_107" "Z_108"
#>  ...（中間省略）...
#> [100] "X_199" "Y_200"
#以上常用來創造新的 id 時使用

# ------------------------------------------------------------
# 第二部分：用中括號 [ ] 取出元素
# ------------------------------------------------------------
################################
#向量基本操作
################################
w = y[3]
#  取第 3 個元素 → 3.1
w = y[0]      #不可以喲！序號由 1 開始，沒有第零號的元素
#  R 不會出錯，而是回傳一個「空的向量」numeric(0)，什麼都沒取到
#  （這比出錯更危險，因為不容易發現）
w = y[1:3]
#  取第 1~3 個元素 → 10.4 5.6 3.1
x[1:10]
#  x 只有 5 個元素，超過範圍的位置會得到 NA（缺失值），也不會出錯
#> [1] 10.4  5.6  3.1  6.4 21.7   NA   NA   NA   NA   NA
w=c("x","y")[rep(c(1,2,2,1,1,2,1,2), times=4)]
w
#  先用 rep() 產生 32 個位置編號（1 或 2），再到 c("x","y") 裡取值：
#  1 → "x"，2 → "y"。同一個位置可以重複取很多次
#> [1] "x" "y" "y" "x" "x" "y" "x" "y" "x" "y" "y" "x" "x" "y" "x" "y" "x" "y" "y"
#> [20] "x" "x" "y" "x" "y" "x" "y" "y" "x" "x" "y" "x" "y"

x=c(1:10)
y=x[-(2:5)]
#  負號代表「去掉」：去掉第 2~5 個 → 1 6 7 8 9 10
y=x[-c(2,3,6,7)]
#  去掉第 2、3、6、7 個 → 1 4 5 8 9 10


