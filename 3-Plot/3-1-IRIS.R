hist(irisVer$Petal.Length,breaks=seq(0,8,l=17),xlim=c(0,8),ylim=c(0,40))
hist(irisSet$Petal.Length,breaks=seq(0,8,l=17),xlim=c(0,8),ylim=c(0,40))
hist(irisVir$Petal.Length,breaks=seq(0,8,l=17),xlim=c(0,8),ylim=c(0,40))
#  breaks = seq(0, 8, l=17)：區間切點是 0, 0.5, 1, ..., 8，共 16 個區間，每格寬 0.5
#  （l 是 length.out 的簡寫）
#  三張圖的區間、x 軸、y 軸範圍都相同，可以直接比較：
#  setosa 的花瓣長度集中在 1~2，明顯比另外兩種短

# ------------------------------------------------------------
# 第六部分：豆莢圖 (beanplot)
# ------------------------------------------------------------
################################
#beamplot
################################

if (!require("beanplot")) install.packages("beanplot")
library(beanplot)
xiris <- iris
xiris$Species <- NULL
#  把某一欄設為 NULL，就是刪除這一欄 → xiris 只剩 4 個數字欄
beanplot(xiris,
         main = "Iris flowers",col=c('#ff8080','#0000FF','#0000FF','#FF00FF'),
         border = "#000000")
#  豆莢圖：結合箱形圖和密度圖，豆莢越寬代表那附近的資料越多，
#  比箱形圖更容易看出資料是否有兩個高峰（例如 Petal.Length）
#  顏色用「#紅綠藍」的 16 進位色碼表示，例如 #FF0000 是紅色、#0000FF 是藍色

##col = the vector of colors stand for the area of the beans,
                      # the lines inside the bean,
                      # the lines outside the bean,
                      # and the average line per bean.
# 【補充】col 的 4 個顏色依序代表：豆莢填色、豆莢內的線、豆莢外的線、平均線
#   border 是豆莢外框的顏色，#000000 是黑色

# ------------------------------------------------------------
# 第七部分：相關係數與散布圖矩陣
# ------------------------------------------------------------
################################
#觀察各維度之間的關聯系數
################################
# 【補充】相關係數 r 介於 -1 ~ 1：
#   接近 1  ：正相關（一個變大，另一個也變大）
#   接近 -1 ：負相關（一個變大，另一個變小）
#   接近 0  ：沒有線性關係


corr <- cor(iris[,1:4])
corr
#  兩兩欄位之間的相關係數，對角線是自己和自己，一定是 1
#>              Sepal.Length Sepal.Width Petal.Length Petal.Width
#> Sepal.Length    1.0000000  -0.1175698    0.8717538   0.8179411
#> Sepal.Width    -0.1175698   1.0000000   -0.4284401  -0.3661259
#> Petal.Length    0.8717538  -0.4284401    1.0000000   0.9628654
#> Petal.Width     0.8179411  -0.3661259    0.9628654   1.0000000
corr <- cor(iris[,1:4])
round(corr,3)     #四捨五入小數第三位
#>              Sepal.Length Sepal.Width Petal.Length Petal.Width
#> Sepal.Length        1.000      -0.118        0.872       0.818
#> Sepal.Width        -0.118       1.000       -0.428      -0.366
#> Petal.Length        0.872      -0.428        1.000       0.963
#> Petal.Width         0.818      -0.366        0.963       1.000
#  花瓣長度和花瓣寬度的相關係數 0.963，幾乎是完全正相關


#捉對比較以散布圖顯示，限numeric
pairs(iris[,1:4])
#  散布圖矩陣：每兩個欄位畫一張散布圖，4 欄共 4 × 3 = 12 張（對角線是欄位名稱）
#  可以和上面的相關係數對照：相關越高，點越接近一條直線
pairs(iris[,1:4], col = iris[,5])
#  col = iris[,5]：依品種上色（R 把類別轉成 1、2、3，對應黑、紅、綠）
#  可以看出 setosa 和另外兩種明顯分開

