# ============================================================
# 2-8 資料離散化 (Discretization)
# ============================================================
# 什麼是離散化？
#   把「連續的數字」切成幾個「區間」，變成類別。
#   例如年齡 0~100 歲切成「兒童、青年、中年、老年」。
#   有些方法（例如決策樹的某些版本、關聯規則）只能處理類別資料，所以要先離散化。
#
# 這個範例介紹兩種方法：
#   1. 等寬切割 (equal width)：infotheo 套件的 discretize()
#   2. ChiMerge 卡方合併法：discretization 套件的 chiM()
#
# 注意：這兩個套件需要先安裝：
#   install.packages("infotheo")
#   install.packages("discretization")
#
# 說明：#> 是 R 4.6.1 實際執行的結果。
# ============================================================

# ------------------------------------------------------------
# 第一部分：等寬切割
# ------------------------------------------------------------
library(infotheo)
myiris<-discretize(iris,"equalwidth",5)
#  discretize(資料, 切割方法, 區間數)
#  "equalwidth" 等寬：把每欄的「最小值 ~ 最大值」平均切成 5 段，每段寬度相同
#    以 Sepal.Length 為例：範圍 4.3 ~ 7.9，寬度 3.6，每段 0.72
#    4.3~5.02 → 1、5.02~5.74 → 2、... 、7.18~7.9 → 5
#  結果每個數字都換成區間編號 1~5
#  另一種方法是 "equalfreq" 等頻：每段的「資料筆數」相同
#
#  注意：Species 是文字類別，也被轉成數字 1、2、3 後一起切割，
#  所以結果變成 1、3、5。通常應該只對數字欄位離散化：discretize(iris[1:4], ...)
#
#  查看前 3 列：head(myiris, 3)
#>   Sepal.Length Sepal.Width Petal.Length Petal.Width Species
#> 1            2           4            1           1       1
#> 2            1           3            1           1       1
#> 3            1           3            1           1       1
#
#  每欄各區間的筆數：sapply(myiris, table)
#  Sepal.Length： 1:32  2:41  3:42  4:24  5:11
#  Petal.Length： 1:50  2:3   3:34  4:47  5:16

table(myiris)
#  table() 計算每種組合出現幾次。
#  這裡丟進 5 個欄位，會產生 5 × 5 × 5 × 5 × 3 個組合的交叉表，輸出非常長，不太好讀。
#  建議一次看一欄或兩欄，例如：
#    table(myiris$Sepal.Length)
#    table(myiris$Petal.Length, iris$Species)   ← 花瓣長度區間 vs 品種
#  原本的輸出開頭如下：
#> , , Petal.Length = 1, Petal.Width = 1, Species = 1
#>
#>             Sepal.Width
#> Sepal.Length  1  2  3  4  5
#>            1  1  1 21  4  0
#>            2  0  0  5 13  3
#>  ...（省略）...



# ------------------------------------------------------------
# 第二部分：ChiMerge 卡方合併法
# ------------------------------------------------------------
library(discretization)
chi1<-chiM(iris,alpha=0.05)
#  chiM(資料, alpha = 顯著水準)
#  ChiMerge 是「監督式」離散化：會參考最後一欄的類別（這裡是 Species）來決定切點。
#  做法：先把每個不同的值各自當成一個區間，再用卡方檢定比較相鄰兩個區間，
#        如果兩個區間的品種分布「沒有顯著差異」，就把它們合併，直到無法再合併。
#  alpha = 0.05 是卡方檢定的顯著水準，數字越小，合併得越多、區間越少
#
#  注意：chiM() 規定「最後一欄必須是類別」，iris 的 Species 剛好在最後一欄
#
#  chi1 是一個 list，有兩個部分：
#    chi1$cutp      ：每一欄的切點
#    chi1$Disc.data ：離散化後的資料
#  chi1$cutp 的結果：
#> [[1]]                    ← Sepal.Length 在 5.45、5.75、7.05 切開，分成 4 段
#> [1] 5.45 5.75 7.05
#> [[2]]                    ← Sepal.Width 分成 3 段
#> [1] 2.95 3.35
#> [[3]]                    ← Petal.Length 分成 4 段
#> [1] 2.45 4.75 5.15
#> [[4]]                    ← Petal.Width 分成 3 段
#> [1] 0.80 1.75
#
#  和等寬切割的差別：每欄的區間數不一樣，切點會選在「最能區分品種」的位置。
#  例如 Petal.Length 在 2.45 切開，剛好把 setosa（花瓣都很短）和其他兩種分開。

# ============================================================
# 重點整理
# ============================================================
# | 方法          | 函數                          | 特色                         |
# |---------------|-------------------------------|------------------------------|
# | 等寬          | discretize(x, "equalwidth", k)| 每段寬度相同，最簡單         |
# | 等頻          | discretize(x, "equalfreq", k) | 每段筆數相同                 |
# | ChiMerge      | chiM(x, alpha)                | 依類別自動決定切點和區間數   |
#
# R 內建的 cut() 也可以離散化，例如：
#   cut(iris$Sepal.Length, breaks = 3)                  ← 等寬切 3 段
#   cut(iris$Sepal.Length, breaks = c(4, 5, 6, 8))      ← 自訂切點
