# 這個範例教你三種「自動產生一串數字」的方法，
# 不用一個一個手打 c(1,2,3,4,...)。
#   seq()      ：產生等差數列，例如 1, 3, 5, 7, 9
#   sequence() ：一次產生好幾段從頭數起的數列，再接在一起
#   rep()      ：把某個值重複很多次
# ============================================================

# 製造連續等差數列
