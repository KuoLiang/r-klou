# ============================================================
# R 語言入門：向量 (vector) 的建立、運算與比較
# ============================================================
# 「向量」是 R 最基本的資料結構，可以想成「一排同類型的資料」。
# 用 c() 把多個值組合成一個向量，c 是 combine（合併）的意思。
#
# 小提醒：R 的賦值可以用 = 或 <-，兩者在這裡效果相同。
#        R 社群習慣用 <-，例如 a <- c(1,2,3)

# ------------------------------------------------------------
# 第一部分：建立向量
# ------------------------------------------------------------
a = c(1,2,3,4,5)          # 數字向量：1 到 5
b = c("1","2","3","4","5")# 文字向量：有加引號 " "，所以是「文字」不是數字！
c = c(5,4,3,2,1)          # 數字向量：5 到 1（倒過來）
e = c(5,4,3,2)            # 數字向量：只有 4 個元素

# 注意：這裡把變數取名為 c，剛好和函數 c() 同名。
# R 會自動分辨「變數 c」和「函數 c()」，所以還能執行，
# 但容易混淆，實務上建議避免用 c、t、mean 這類函數名稱當變數名。

# ------------------------------------------------------------
# 第二部分：length() 查看向量長度（有幾個元素）
# ------------------------------------------------------------
length(a)   # a 有幾個元素？
#> [1] 5
length(b)
#> [1] 5
length(c)
#> [1] 5
length(e)   # e 只有 4 個元素
#> [1] 4

# 補充：輸出前面的 [1] 不是答案，而是「這一行從第 1 個元素開始」的標記。

# ------------------------------------------------------------
# 第三部分：mode() 查看資料型態
# ------------------------------------------------------------
mode(a)     # 數字型
#> [1] "numeric"
mode(b)     # 文字型（字串）
#> [1] "character"
mode(c)
#> [1] "numeric"
mode(e)
#> [1] "numeric"

# 重點：b 看起來是 1~5，但因為加了引號，R 把它們當成「文字」，
# 就像 "蘋果" 一樣，不能拿來做數學運算。

# ------------------------------------------------------------
# 第四部分：向量和單一數字的運算
# ------------------------------------------------------------
# R 會把運算「自動套用到每一個元素」，不需要寫迴圈，
# 這叫做「向量化運算」(vectorization)，是 R 很重要的特色。

a/3         # a 的每個元素都除以 3
#> [1] 0.3333333 0.6666667 1.0000000 1.3333333 1.6666667

b/3         # 錯誤！文字不能做除法
#> Error in b/3 : non-numeric argument to binary operator
#  錯誤訊息意思：「二元運算子遇到非數字的參數」
#  如果真的要算，要先轉成數字：as.numeric(b) / 3

c/3
#> [1] 1.6666667 1.3333333 1.0000000 0.6666667 0.3333333
e/3
#> [1] 1.6666667 1.3333333 1.0000000 0.6666667

# ------------------------------------------------------------
# 第五部分：向量和向量的運算
# ------------------------------------------------------------
# 兩個向量運算時，R 會「對應位置」一對一計算：
# 第 1 個和第 1 個、第 2 個和第 2 個……

d = a+c     # (1+5, 2+4, 3+3, 4+2, 5+1)
d           # 單獨打變數名稱，就會印出它的內容
#> [1] 6 6 6 6 6

d = a/c     # (1/5, 2/4, 3/3, 4/2, 5/1)
# 賦值時不會顯示結果，想看要再輸入 d
#  d 的內容是：0.2 0.5 1.0 2.0 5.0

d = a/e     # 警告！a 有 5 個元素，e 只有 4 個，長度不一樣
#> Warning message:
#> In a/e : longer object length is not a multiple of shorter object length
#  警告訊息意思：「較長物件的長度不是較短物件長度的倍數」
#
#  R 的「循環規則」(recycling)：短的向量會從頭重複使用。
#  所以實際計算是：1/5, 2/4, 3/3, 4/2, 5/5  ← 最後的 5 又用了 e 的第 1 個
#  結果：0.2 0.5 1.0 2.0 1.0
#
#  Error（錯誤）和 Warning（警告）的差別：
#  - Error：程式停止，沒有產生結果
#  - Warning：程式照樣執行並產生結果，但 R 提醒你「這可能不是你要的」

##### 

# ------------------------------------------------------------
# 第六部分：用中括號 [ ] 取出向量中的元素（索引）
# ------------------------------------------------------------
# 注意：R 的位置從 1 開始算（不像 Python、C 從 0 開始）

c[1]        # 取出 c 的第 1 個元素
#> [1] 5
c[c(1,3)]   # 同時取出第 1 和第 3 個元素
#> [1] 5 3
#  這裡的 c(1,3) 是「函數 c()」，用來組合位置 1 和 3；
#  外面的 c[ ] 則是「變數 c」。這就是變數取名 c 容易混淆的例子。

# ------------------------------------------------------------
# 第七部分：比較運算，結果是 TRUE / FALSE（邏輯值）
# ------------------------------------------------------------
# 常用比較符號：<  >  <=  >=  ==（等於，兩個等號！） !=（不等於）

a<3         # a 的每個元素是否小於 3？
#> [1]  TRUE  TRUE FALSE FALSE FALSE
#  (1<3, 2<3, 3<3, 4<3, 5<3)

a<c         # a 和 c 對應位置逐一比較
#> [1]  TRUE  TRUE FALSE FALSE FALSE
#  (1<5, 2<4, 3<3, 4<2, 5<1)

# ------------------------------------------------------------
# 第八部分：any() 和 all() 彙總邏輯結果
# ------------------------------------------------------------
# any()：只要「有任何一個」是 TRUE，就回傳 TRUE（像「或」）
# all()：必須「全部都」是 TRUE，才回傳 TRUE（像「且」）

any(a<c)    # 有沒有任何一個 a 小於 c？有（前兩個）
#> [1] TRUE
any(a<=c)   # 有沒有任何一個 a 小於或等於 c？有
#> [1] TRUE
all(a>c)    # 是不是全部的 a 都大於 c？不是
#> [1] FALSE
all(a>=c)   # 是不是全部的 a 都大於或等於 c？不是（1>=5 就不成立）
#> [1] FALSE

