# ============================================================
# R 的向量 (vector) 練習
# 包含：向量運算、循環補齊 (recycling)、比較、索引取值
# ============================================================

# --- 指定值的兩種寫法 ---
a = c(1,2,3,4,5)     # 用 = 指定值（保留作為對照）
a <- c(1,2,3,4,5)    # 用 <- 指定值，結果完全相同；R 社群習慣用 <-
#To insert the <- operator in RStudio:
#Windows & Linux: Press Alt + - (the Alt key and the minus sign).
#Mac: Press Option + - (the Option key and the minus sign).
# RStudio 快捷鍵：Windows/Linux 按 Alt + -，Mac 按 Option + -

b <- 2               # 單一數字在 R 裡其實也是「長度為 1 的向量」

#vector operation
# --- 向量和單一數字的運算 ---
# 單一數字會套用到向量的「每一個」元素
c <- a + b           # c(1,2,3,4,5) + 2 → 3 4 5 6 7
d <- a * b           # c(1,2,3,4,5) * 2 → 2 4 6 8 10

# --- 兩個等長向量的運算：逐一元素對應計算 ---
e <- c(5,4,3,2,1)
f <- a + e           # 1+5, 2+4, 3+3, 4+2, 5+1 → 6 6 6 6 6
g <- a * e           # 1*5, 2*4, 3*3, 4*2, 5*1 → 5 8 9 8 5

# --- 長度不同的向量運算：循環補齊 (recycling) ---
# 短的向量會「重複使用」直到和長的一樣長
h <- c(1,2)
i <- a + h           # h 被補成 1 2 1 2 1 → 2 4 4 6 6
# 會出現警告：長度 5 不是長度 2 的倍數
j <- a * h           # 1*1, 2*2, 3*1, 4*2, 5*1 → 1 4 3 8 5（同樣有警告）
# 提醒：警告不會讓程式停下來，但通常代表長度搞錯了，要留意

# --- 向量比較：結果是邏輯向量 ---
a < e                # 1<5, 2<4, 3<3, 4<2, 5<1 → TRUE TRUE FALSE FALSE FALSE

a <= e               # → TRUE TRUE TRUE FALSE FALSE

any(a<e)             # any()：只要「有一個」是 TRUE 就回傳 TRUE → TRUE

all(a<e)             # all()：「全部」都是 TRUE 才回傳 TRUE → FALSE

# --- 索引取值：用 [ ] 取出向量中的元素 ---
# 注意：R 的索引從 1 開始（不是 0）
a[3]                 # 取第 3 個元素 → 3

a[-c(1:2)]           # 負號代表「排除」：去掉第 1、2 個元素 → 3 4 5
# 1:2 會產生 1 2，所以 c() 可省略，寫 a[-(1:2)] 結果相同

a[c(1,3,5)]          # 一次取多個位置：第 1、3、5 個 → 1 3 5

#循環補齊：這是 R 很常用、也很容易出錯的特性。長度剛好是倍數時（例如 6 和 2）不會有任何警告，所以要特別留意。